// Прогресс по достижению для профиля: {done, cur, goal}
export function achProgress(a, data) {
  const s = (data && data.s) || {}, sets = (data && data.sets) || {};
  if ((data && data.ach && data.ach[a.id])) return { done: true, cur: a.goal || 1, goal: a.goal || 1 };
  if (a.kind === 'count' || a.kind === 'max') return { done: false, cur: Math.min(a.goal, Math.floor(s[a.stat] || 0)), goal: a.goal };
  if (a.kind === 'set') return { done: false, cur: (sets[a.stat] || []).includes(a.item) ? 1 : 0, goal: 1 };
  return { done: false, cur: 0, goal: 1 };
}
